import { describe, expect, test } from "bun:test";
import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { hashPassword, verifyPassword } from "@qala/core";
import { findBin } from "../../cli/src/util";
import { nativeArgs } from "../../cli/src/native";

const FIXTURES: { pw: string; hash: string }[] = JSON.parse(readFileSync(join(import.meta.dir, "fixtures", "password-hashes.json"), "utf8"));
const PASSWORD_MODULE = join(import.meta.dir, "..", "src", "crypto", "password.ts");

describe("password (Bun)", () => {
  test("verifies hashes generated by Bun.password and rejects wrong passwords", async () => {
    expect(FIXTURES.length).toBe(20);
    for (const f of FIXTURES) {
      expect(await verifyPassword(f.pw, f.hash)).toBe(true);
      expect(await verifyPassword(`${f.pw}x`, f.hash)).toBe(false);
    }
  });

  test("hashPassword writes argon2id PHC strings that Bun.password accepts", async () => {
    const hash = await hashPassword("correct horse battery staple");
    expect(hash).toMatch(/^\$argon2id\$v=19\$m=65536,t=2,p=1\$/);
    expect(await Bun.password.verify("correct horse battery staple", hash)).toBe(true);
    expect(await verifyPassword("correct horse battery staple", hash)).toBe(true);
    expect(await verifyPassword("wrong", hash)).toBe(false);
    expect(await hashPassword("correct horse battery staple")).not.toBe(hash);
  });

  test("options and malformed input", async () => {
    const hash = await hashPassword("pw", { memoryKiB: 1024, passes: 1 });
    expect(hash).toContain("m=1024,t=1,p=1");
    expect(await verifyPassword("pw", hash)).toBe(true);
    expect(await verifyPassword("pw", "")).toBe(false);
    expect(await verifyPassword("pw", "$argon2id$garbage")).toBe(false);
    expect(await verifyPassword("pw", "plaintext")).toBe(false);
    expect(hashPassword("pw", { passes: 0 })).rejects.toThrow(RangeError);
    expect(hashPassword("pw", { memoryKiB: 4 })).rejects.toThrow(RangeError);
  });

  test("unicode passwords; empty passwords are refused", async () => {
    for (const pw of ["pässwörd-日本語-🔑"]) {
      const hash = await hashPassword(pw, { memoryKiB: 256, passes: 1 });
      expect(await verifyPassword(pw, hash)).toBe(true);
      expect(await verifyPassword(`${pw}.`, hash)).toBe(false);
    }
    expect(hashPassword("")).rejects.toThrow(RangeError);
    expect(await verifyPassword("", FIXTURES[0]!.hash)).toBe(false);
  });
});

const scriptc = findBin("scriptc", [join(import.meta.dir, "..", "..", "..")]);
const hasCc = spawnSync("cc", ["--version"]).status === 0 && existsSync("/usr/include/sodium.h");

describe.skipIf(scriptc === null || !hasCc)("password (scriptc native binary, libsodium)", () => {
  test("verifies Bun fixtures, interoperates with Bun.password", async () => {
    const dir = mkdtempSync(join(tmpdir(), "qala-password-"));
    try {
      mkdirSync(join(dir, "app"));
      writeFileSync(
        join(dir, "app", "main.ts"),
        `import { hashPassword, verifyPassword } from ${JSON.stringify(PASSWORD_MODULE.replace(/\.ts$/, ""))};
const fixtures: { pw: string; hash: string }[] = ${JSON.stringify(FIXTURES)};
async function main(): Promise<void> {
  let bad = 0;
  for (const f of fixtures) {
    if (!(await verifyPassword(f.pw, f.hash))) bad++;
    if (await verifyPassword(f.pw + "x", f.hash)) bad++;
  }
  console.log("fixture-failures " + bad);
  console.log(await hashPassword(process.argv[2] ?? "pw"));
  console.log(await verifyPassword("garbage", "$argon2id$nope"));
}
main();
`,
      );
      const args = nativeArgs(dir);
      expect(args[0]).toBe("--ffi");
      const out = join(dir, "main");
      const build = spawnSync(scriptc!, ["build", join(dir, "app", "main.ts"), "--node-islands=off", "--optimization", "speed", ...args, "-o", out], { encoding: "utf8" });
      expect(build.stderr + build.stdout).not.toContain("error");
      expect(build.status).toBe(0);
      const run = spawnSync(out, ["s3cret-ü"], { encoding: "utf8" });
      const [failures, hash, garbage] = run.stdout.trim().split("\n");
      expect(failures).toBe("fixture-failures 0");
      expect(hash).toMatch(/^\$argon2id\$v=19\$m=65536,t=2,p=1\$/);
      expect(garbage).toBe("false");
      expect(await Bun.password.verify("s3cret-ü", hash!)).toBe(true);
      expect(await Bun.password.verify("s3cret", hash!)).toBe(false);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  }, 120000);
});
