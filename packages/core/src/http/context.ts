import type { Container, Token } from "../container";
import { Logger } from "../log";
import { parseCookies, serializeCookie, type CookieOptions } from "./cookie";
import { decodeUtf8 } from "./multipart";

/**
 * One incoming request as the framework sees it (independent of the HTTP server underneath).
 * The body is kept as bytes (`raw`) and decoded to text (`body`) only when asked for, so binary
 * uploads are never decoded as UTF-8. Pass the text, or `""` plus the bytes as `raw`.
 */
export class RequestData {
  private text: string | null;
  private bytes: Uint8Array | null;

  constructor(
    readonly method: string,
    /** Path and query string, e.g. `/tasks?done=true`. */
    readonly url: string,
    /** Lower-cased header names. */
    readonly headers: Record<string, string>,
    body: string,
    readonly ip: string,
    raw: Uint8Array | null = null,
  ) {
    this.bytes = raw;
    this.text = raw === null ? body : null;
  }

  /** The body decoded as UTF-8 (decoded on first use). */
  get body(): string {
    if (this.text === null) this.text = decodeUtf8(this.bytes!);
    return this.text;
  }

  /** The body bytes, exactly as received. */
  get raw(): Uint8Array {
    if (this.bytes === null) this.bytes = new Uint8Array(Buffer.from(this.text!, "utf8"));
    return this.bytes;
  }

  /** Whether the body is empty (without decoding it). */
  get empty(): boolean {
    return this.bytes === null ? this.text === "" : this.bytes.length === 0;
  }
}

/**
 * The request context middleware and handlers share: the raw request, route params, query and
 * a per-request store (`ctx.set("user", user)`), e.g. for authentication results.
 */
export class Context {
  /** Validated params/query/body, set before the handler runs. */
  params: Record<string, string> = {};
  query: Record<string, string> = {};
  /** Response headers added by middleware or handlers. */
  readonly responseHeaders: Record<string, string> = {};
  /** `Set-Cookie` header values added by middleware or handlers (one entry per cookie). */
  readonly responseCookies: string[] = [];
  private cookies: Record<string, string> | null = null;
  private readonly store = new Map<string, unknown>();
  readonly startedAt = Date.now();
  /** The request id (`x-request-id`, validated, or generated by the app); "" outside an app. */
  requestId = "";
  /** The app's logger; `log` derives the per-request logger from it. */
  logger: Logger | null = null;
  private requestLog: Logger | null = null;

  constructor(
    readonly request: RequestData,
    readonly path: string,
    /** The app's DI container (null for a context built outside an app). */
    readonly container: Container | null = null,
  ) {}

  /** A service from the app's container, for middleware: `ctx.service(AuthService)`. */
  service<T>(token: Token<T>): T {
    if (this.container === null) throw new Error("This context has no container");
    return this.container.get(token);
  }

  /** A logger that adds `request_id` to every line: `ctx.log.info("Task created", { id })`. */
  get log(): Logger {
    if (this.requestLog === null) {
      const base = this.logger ?? new Logger();
      this.requestLog = this.requestId === "" ? base : base.child({ request_id: this.requestId });
    }
    return this.requestLog;
  }

  get method(): string {
    return this.request.method;
  }

  header(name: string): string | undefined {
    return this.request.headers[name.toLowerCase()];
  }

  /** The bearer token of the `Authorization` header, if any. */
  bearer(): string | undefined {
    const value = this.header("authorization");
    if (value === undefined || !value.toLowerCase().startsWith("bearer ")) return undefined;
    return value.slice(7).trim();
  }

  set(key: string, value: unknown): void {
    this.store.set(key, value);
  }

  get(key: string): unknown {
    return this.store.get(key);
  }

  /** A request cookie by name (from the `Cookie` header), or `undefined`. */
  cookie(name: string): string | undefined {
    if (this.cookies === null) this.cookies = parseCookies(this.header("cookie") ?? "");
    return this.cookies[name];
  }

  /** All request cookies. */
  allCookies(): Record<string, string> {
    if (this.cookies === null) this.cookies = parseCookies(this.header("cookie") ?? "");
    return this.cookies;
  }

  /** Adds a `Set-Cookie` header to the response; several cookies are sent as several headers. */
  setCookie(name: string, value: string, options: CookieOptions = {}): void {
    this.responseCookies.push(serializeCookie(name, value, options));
  }

  /** Expires a cookie in the browser (pass the same `path`/`domain` it was set with). */
  clearCookie(name: string, options: CookieOptions = {}): void {
    this.responseCookies.push(serializeCookie(name, "", { path: options.path, domain: options.domain, httpOnly: options.httpOnly, secure: options.secure, sameSite: options.sameSite, maxAge: 0, expires: new Date(0) }));
  }

  setHeader(name: string, value: string): void {
    this.responseHeaders[name.toLowerCase()] = value;
  }
}

/** Splits `/a/b?x=1&y=2` into path and decoded query values. */
export function splitUrl(url: string): { path: string; query: Record<string, string> } {
  const mark = url.indexOf("?");
  const rawPath = mark === -1 ? url : url.slice(0, mark);
  const query: Record<string, string> = {};
  if (mark !== -1) {
    for (const pair of url.slice(mark + 1).split("&")) {
      if (pair === "") continue;
      const eq = pair.indexOf("=");
      const key = decode(eq === -1 ? pair : pair.slice(0, eq));
      query[key] = eq === -1 ? "" : decode(pair.slice(eq + 1));
    }
  }
  let path = rawPath === "" ? "/" : rawPath;
  if (path.length > 1 && path.endsWith("/")) path = path.slice(0, -1);
  return { path, query };
}

function decode(s: string): string {
  try {
    return decodeURIComponent(s.replace(/\+/g, " "));
  } catch {
    return s;
  }
}

const REQUEST_ID = /^[A-Za-z0-9._:@\/+=-]{1,128}$/;

/** Whether an incoming `x-request-id` is safe to reuse: 1–128 characters of `A-Z a-z 0-9 . _ : @ / + = -`. */
export function validRequestId(value: string): boolean {
  return REQUEST_ID.test(value);
}
