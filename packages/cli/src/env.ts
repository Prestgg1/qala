import { existsSync, readFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { CliError, LAYOUT, writeIfChanged } from "./util";

export const ENV_EXAMPLE = ".env.example";
export const ENV_GEN = "env.gen.ts";

export type EnvEntry = { key: string; type: "string" | "number" | "boolean" | "url" | "enum"; values: string[]; fallback: string | undefined; required: boolean; line: number };

/**
 * Parses `.env.example`: `KEY=default # type: number|boolean|string|url|enum(a,b) required?`.
 * No type comment means string; an empty default or the word `required` makes the variable required.
 */
export function parseEnvExample(text: string): EnvEntry[] {
  const out: EnvEntry[] = [];
  const seen = new Set<string>();
  text.split("\n").forEach((raw, i) => {
    const line = raw.trim();
    if (line === "" || line.startsWith("#")) return;
    const eq = line.indexOf("=");
    if (eq <= 0) return;
    const key = line.slice(0, eq).trim().replace(/^export\s+/, "");
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) throw new CliError(`${ENV_EXAMPLE}:${i + 1}: "${key}" is not a valid variable name`);
    if (seen.has(key)) throw new CliError(`${ENV_EXAMPLE}:${i + 1}: ${key} is declared twice`);
    seen.add(key);
    let rest = line.slice(eq + 1).trim();
    let comment = "";
    if (rest.startsWith('"') || rest.startsWith("'")) {
      const end = rest.indexOf(rest[0]!, 1);
      if (end === -1) throw new CliError(`${ENV_EXAMPLE}:${i + 1}: unterminated quote`);
      comment = rest.slice(end + 1);
      rest = rest.slice(1, end);
      comment = comment.slice(comment.indexOf("#") === -1 ? comment.length : comment.indexOf("#"));
    } else {
      const hash = rest.search(/\s#/);
      if (rest.startsWith("#")) {
        comment = rest;
        rest = "";
      } else if (hash !== -1) {
        comment = rest.slice(hash + 1);
        rest = rest.slice(0, hash).trim();
      }
    }
    let type: EnvEntry["type"] = "string";
    let values: string[] = [];
    let required = rest === "";
    const m = comment.match(/#\s*type:\s*(.*)$/);
    if (m !== null) {
      const spec = m[1]!.trim();
      const word = spec.match(/^(string|number|boolean|url)\b/);
      const en = spec.match(/^enum\(([^)]*)\)/);
      if (en !== null) {
        type = "enum";
        values = en[1]!.split(",").map((v) => v.trim()).filter((v) => v !== "");
        if (values.length === 0) throw new CliError(`${ENV_EXAMPLE}:${i + 1}: enum() needs at least one value`);
      } else if (word !== null) type = word[1] as EnvEntry["type"];
      else throw new CliError(`${ENV_EXAMPLE}:${i + 1}: unknown type "${spec}" (use string, number, boolean, url or enum(a,b))`);
      if (/\brequired\b/.test(spec.replace(/^enum\([^)]*\)/, ""))) required = true;
    }
    if (!required) {
      if (type === "number" && !Number.isFinite(Number(rest))) throw new CliError(`${ENV_EXAMPLE}:${i + 1}: ${key} default "${rest}" is not a number`);
      if (type === "boolean" && !["true", "false", "1", "0", "yes", "no"].includes(rest)) throw new CliError(`${ENV_EXAMPLE}:${i + 1}: ${key} default "${rest}" is not a boolean`);
      if (type === "enum" && !values.includes(rest)) throw new CliError(`${ENV_EXAMPLE}:${i + 1}: ${key} default "${rest}" is not one of ${values.join(", ")}`);
    }
    out.push({ key, type, values, fallback: required ? undefined : rest, required, line: i + 1 });
  });
  return out;
}

function expression(e: EnvEntry): string {
  const k = JSON.stringify(e.key);
  const fb = e.fallback;
  switch (e.type) {
    case "number":
      return fb === undefined ? `e.number(${k})` : `e.number(${k}, ${Number(fb)})`;
    case "boolean":
      return fb === undefined ? `e.boolean(${k})` : `e.boolean(${k}, ${["true", "1", "yes"].includes(fb)})`;
    case "url":
      return fb === undefined ? `e.url(${k})` : `e.url(${k}, ${JSON.stringify(fb)})`;
    case "enum": {
      const list = `[${e.values.map((v) => JSON.stringify(v)).join(", ")}] as const`;
      return fb === undefined ? `e.oneOf(${k}, ${list})` : `e.oneOf(${k}, ${list}, ${JSON.stringify(fb)})`;
    }
    default:
      return fb === undefined ? `e.string(${k})` : `e.string(${k}, ${JSON.stringify(fb)})`;
  }
}

export function renderEnv(entries: EnvEntry[]): string {
  const lines = [
    "// Generated by `qala generate` from .env.example. Do not edit: changes are overwritten.",
    "",
    'import { defineConfig } from "@qala/core";',
    "",
    "/** Typed environment: validated at startup, every missing or invalid variable reported at once. */",
    "export const env = defineConfig((e) => ({",
  ];
  for (const e of entries) lines.push(`  ${JSON.stringify(e.key)}: ${expression(e)},`);
  lines.push("}));", "");
  return lines.join("\n").replace(/^(\s+)"([A-Za-z_][A-Za-z0-9_]*)":/gm, "$1$2:");
}

/** Writes `.qala/env.gen.ts` when the app has a `.env.example`; removes a stale one. Returns the relative path if written. */
export function generateEnv(root: string): string | null {
  const dir = join(root, LAYOUT.generated);
  const file = join(dir, ENV_GEN);
  const example = join(root, ENV_EXAMPLE);
  if (!existsSync(example)) {
    if (existsSync(file)) rmSync(file);
    return null;
  }
  const changed = writeIfChanged(file, renderEnv(parseEnvExample(readFileSync(example, "utf8"))));
  return changed ? `${LAYOUT.generated}/${ENV_GEN}` : null;
}
