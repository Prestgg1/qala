import { existsSync, rmSync } from "node:fs";
import { join } from "node:path";
import { type ModelInfo, renderModels, scanModels, type SkippedModel } from "./models";
import { type ControllerInfo, joinPath, scanControllers } from "./scan";
import { LAYOUT, importPath, pascal, writeIfChanged } from "./util";

const HEADER = "// Generated by `qala generate`. Do not edit: changes are overwritten.\n";

export type Generated = { controllers: ControllerInfo[]; models: ModelInfo[]; skippedModels: SkippedModel[]; written: string[] };

/** The local alias each controller is imported under (unique even when two files export the same name). */
function alias(c: ControllerInfo): string {
  return `${pascal(c.name)}Controller`;
}

function importLine(c: ControllerInfo, fromDir: string, typeOnly: boolean): string {
  const a = alias(c);
  const what = a === c.exportName ? a : `${c.exportName} as ${a}`;
  return `import ${typeOnly ? "type " : ""}{ ${what} } from "${importPath(fromDir, c.file)}";`;
}

export function renderRoutes(root: string, controllers: ControllerInfo[]): string {
  const dir = join(root, LAYOUT.generated);
  const lines = [HEADER, 'import type { ControllerEntry } from "@qala/core";'];
  for (const c of controllers) lines.push(importLine(c, dir, false));
  lines.push("", "export const controllers: ControllerEntry[] = [");
  for (const c of controllers) lines.push(`  { name: ${JSON.stringify(c.name)}, prefix: ${JSON.stringify(c.prefix)}, controller: ${alias(c)} },`);
  lines.push("];", "");
  return lines.join("\n");
}

export function renderApi(root: string, controllers: ControllerInfo[]): string {
  const dir = join(root, LAYOUT.generated);
  const lines = [
    HEADER,
    "// The frontend contract: `import { manifest, type Api } from \"<backend>/.qala/api\"` and",
    "// `createClient<Api>({ baseUrl, manifest })` from @qala/client. Only types cross over; no server code.",
  ];
  for (const c of controllers) lines.push(importLine(c, dir, true));
  lines.push("", "export type Api = {");
  for (const c of controllers) lines.push(`  ${c.name}: typeof ${alias(c)};`);
  lines.push("};", "", "export const manifest = {");
  for (const c of controllers) {
    const actions = c.actions.map((a) => `${a.name}: [${JSON.stringify(a.method)}, ${JSON.stringify(joinPath(c.prefix, a.path))}]`);
    lines.push(`  ${c.name}: { ${actions.join(", ")} },`);
  }
  lines.push("} as const;", "");
  return lines.join("\n");
}

export function renderMain(root: string, hasModels = false): string {
  const dir = join(root, LAYOUT.generated);
  const hasProviders = existsSync(join(root, LAYOUT.providers));
  const hasKernel = existsSync(join(root, LAYOUT.kernel));
  const hasConfig = existsSync(join(root, LAYOUT.config));
  const lines = [HEADER, 'import { createApp, serve } from "@qala/core";'];
  // Registers the generated row decoders on the models before anything queries them.
  if (hasModels) lines.push('import "./models.gen";');
  if (hasConfig) lines.push(`import { config } from "${importPath(dir, join(root, LAYOUT.config))}";`);
  if (hasProviders) lines.push(`import { providers } from "${importPath(dir, join(root, LAYOUT.providers))}";`);
  if (hasKernel) lines.push(`import { kernel } from "${importPath(dir, join(root, LAYOUT.kernel))}";`);
  lines.push('import { controllers } from "./routes.gen";', "");
  lines.push("const app = createApp({");
  lines.push("  controllers,");
  if (hasProviders) lines.push("  providers,");
  if (hasKernel) lines.push("  middleware: kernel.middleware,", "  onError: kernel.onError,", "  exposeErrors: kernel.exposeErrors,");
  lines.push("});", "");
  lines.push(hasConfig ? "serve(app, { port: config.port });" : 'serve(app, { port: Number(process.env.PORT ?? "3000") });', "");
  return lines.join("\n");
}

/**
 * Scans controllers and models and (re)writes `.qala/routes.gen.ts`, `.qala/api.ts`, `.qala/main.ts`
 * and, when the app has models, `.qala/models.gen.ts` (typed row decoders compiled statically by scriptc).
 */
export function generate(root: string): Generated {
  const controllers = scanControllers(root);
  const { models, skipped } = scanModels(root);
  const dir = join(root, LAYOUT.generated);
  const written: string[] = [];
  const hasModels = models.length > 0;
  const files: [string, string][] = [
    ["routes.gen.ts", renderRoutes(root, controllers)],
    ["api.ts", renderApi(root, controllers)],
  ];
  if (hasModels) files.push(["models.gen.ts", renderModels(root, models)]);
  files.push(["main.ts", renderMain(root, hasModels)]);
  for (const [name, content] of files) if (writeIfChanged(join(dir, name), content)) written.push(`${LAYOUT.generated}/${name}`);
  const stale = join(dir, "models.gen.ts");
  if (!hasModels && existsSync(stale)) rmSync(stale);
  return { controllers, models, skippedModels: skipped, written };
}
