import { tmpdir } from "node:os";
import { join } from "node:path";
import { openApiConfig } from "@qala/openapi/load";
import { generateEnv } from "./env";
import { type ModelInfo, renderModels, scanModels, type SkippedModel } from "./models";
import { generateQueries, QUERIES_GEN } from "./queries";
import { assertProviders, generateProviders } from "./di";
import { type ControllerInfo, joinPath, scanControllers } from "./scan";
import { CliError, LAYOUT, importPath, pascal, writeIfChanged } from "./util";

const HEADER = "// Generated by `qala generate`. Do not edit: changes are overwritten.\n";

export type Generated = {
  controllers: ControllerInfo[];
  models: ModelInfo[];
  skippedModels: SkippedModel[];
  written: string[];
  queries: number;
  /** Providers generated from constructor types, and DI warnings (app/providers.ts too dynamic to read fully). */
  providers: number;
  diWarnings: string[];
};

export const PROVIDERS_GEN = "providers.gen.ts";

/** The local alias each controller is imported under (unique even when two files export the same name). */
function alias(c: ControllerInfo): string {
  return `${pascal(c.name)}Controller`;
}

function importLine(c: ControllerInfo, fromDir: string, typeOnly: boolean): string {
  const a = alias(c);
  const what = a === c.exportName ? a : `${c.exportName} as ${a}`;
  return `import ${typeOnly ? "type " : ""}{ ${what} } from "${importPath(fromDir, c.file)}";`;
}

/** The controller value a route entry registers: function controllers as they are, class controllers wrapped. */
function controllerValue(c: ControllerInfo): string {
  const a = alias(c);
  if (c.kind === "function") return c.auth ? `${a}.withAuth()` : a;
  const pick = c.actions.map((x) => `${x.name}: x.${x.name}`).join(", ");
  const options: string[] = [];
  if (c.staticMiddleware) options.push(`middleware: ${a}.middleware`);
  if (c.auth) options.push("auth: true");
  return `classController<${a}>(${a}, (x) => ({ ${pick} })${options.length > 0 ? `, { ${options.join(", ")} }` : ""})`;
}

export function renderRoutes(root: string, controllers: ControllerInfo[]): string {
  const dir = join(root, LAYOUT.generated);
  const hasClass = controllers.some((c) => c.kind === "class");
  const lines = [HEADER, hasClass ? 'import { classController, type ControllerEntry } from "@qala/core";' : 'import type { ControllerEntry } from "@qala/core";'];
  for (const c of controllers) lines.push(importLine(c, dir, false));
  lines.push("", "export const controllers: ControllerEntry[] = [");
  for (const c of controllers) lines.push(`  { name: ${JSON.stringify(c.name)}, prefix: ${JSON.stringify(c.prefix)}, controller: ${controllerValue(c)} },`);
  lines.push("];", "");
  return lines.join("\n");
}

export function renderApi(root: string, controllers: ControllerInfo[]): string {
  const dir = join(root, LAYOUT.generated);
  const lines = [
    HEADER,
    "// The frontend contract: `import { manifest, type Api } from \"<backend>/.qala/api\"` and",
    "// `createClient<Api>({ baseUrl, manifest })` from @qala/client. Only types cross over; no server code.",
  ];
  if (controllers.some((c) => c.kind === "class")) lines.push('import type { ClassController } from "@qala/core";');
  if (hasAppUser(root)) lines.push('import type {} from "./auth.gen";');
  for (const c of controllers) lines.push(importLine(c, dir, true));
  lines.push("", "export type Api = {");
  for (const c of controllers) lines.push(c.kind === "class" ? `  ${c.name}: ClassController<${alias(c)}>;` : `  ${c.name}: typeof ${alias(c)};`);
  lines.push("};", "", "export const manifest = {");
  for (const c of controllers) {
    const actions = c.actions.map((a) => `${a.name}: [${JSON.stringify(a.method)}, ${JSON.stringify(joinPath(c.prefix, a.path))}]`);
    lines.push(`  ${c.name}: { ${actions.join(", ")} },`);
  }
  lines.push("} as const;", "");
  return lines.join("\n");
}

export function renderMain(root: string, hasModels = false, hasGeneratedProviders = false): string {
  const dir = join(root, LAYOUT.generated);
  const hasProviders = existsSync(join(root, LAYOUT.providers));
  const hasKernel = existsSync(join(root, LAYOUT.kernel));
  const hasConfig = existsSync(join(root, LAYOUT.config));
  const lines = [HEADER, 'import { createApp, serve } from "@qala/core";'];
  // Registers the generated row decoders on the models before anything queries them.
  if (hasModels) lines.push('import "./models.gen";');
  if (hasConfig) lines.push(`import { config } from "${importPath(dir, join(root, LAYOUT.config))}";`);
  const envExample = join(root, ".env.example");
  const envPort = !hasConfig && existsSync(envExample) && /^\s*PORT\s*=.*#\s*type:\s*number/m.test(readFileSync(envExample, "utf8"));
  if (envPort) lines.push('import { env } from "./env.gen";');
  if (hasGeneratedProviders) lines.push('import { generatedProviders } from "./providers.gen";');
  // `export async function authenticate(ctx)` in app/auth.ts resolves the user for `auth: true` / `(auth)` routes.
  const authFile = join(root, "app/auth.ts");
  const hasAuthenticate = existsSync(authFile) && /export\s+(async\s+)?function\s+authenticate\b|export\s+const\s+authenticate\b/.test(readFileSync(authFile, "utf8"));
  if (hasAuthenticate) lines.push(`import { authenticate } from "${importPath(dir, authFile)}";`);
  // Types `user` as app/auth.ts's AppUser in handlers (declaration merging; no runtime code).
  if (hasAppUser(root)) lines.push('import "./auth.gen";');
  if (hasProviders) lines.push(`import { providers } from "${importPath(dir, join(root, LAYOUT.providers))}";`);
  // `export const serveOptions` in app/kernel.ts (workers, bodyLimit, host) is passed on to serve().
  const kernelSource = hasKernel ? readFileSync(join(root, LAYOUT.kernel), "utf8") : "";
  const hasServeOptions = /export\s+const\s+serveOptions\b/.test(kernelSource);
  // `export function onStart(app, { primary })` in app/kernel.ts runs once per process after the server listens
  // (primary is false in worker processes, so once-per-deployment jobs can be limited to the primary).
  const hasOnStart = /export\s+(async\s+)?function\s+onStart\b|export\s+const\s+onStart\b/.test(kernelSource);
  if (hasOnStart) lines[1] = 'import { createApp, isWorker, serve } from "@qala/core";';
  // `export function onShutdown(app)` runs on SIGTERM/SIGINT after in-flight requests finished, before the pool closes.
  const hasOnShutdown = /export\s+(async\s+)?function\s+onShutdown\b|export\s+const\s+onShutdown\b/.test(kernelSource);
  if (hasKernel) lines.push(`import { kernel${hasServeOptions ? ", serveOptions" : ""}${hasOnStart ? ", onStart" : ""}${hasOnShutdown ? ", onShutdown" : ""} } from "${importPath(dir, join(root, LAYOUT.kernel))}";`);
  // Model event handlers (`on(Task, "created", …)`) register themselves when app/events/*.ts is imported.
  const eventFiles = eventModules(root);
  for (const file of eventFiles) lines.push(`import "${importPath(dir, file)}";`);
  const bindsEvents = eventFiles.length > 0 || hasModels;
  if (bindsEvents) lines.push('import { bindEvents } from "@qala/core";');
  // `"qala": { "openapi": { "serve": true } }` in package.json serves the generated document at /openapi.json.
  const serveOpenApi = openApiConfig(root)?.serve === true;
  if (serveOpenApi) lines.push(`import { ${OPENAPI_EXPORT} } from "./openapi.gen";`);
  lines.push('import { controllers } from "./routes.gen";', "");
  lines.push("const app = createApp({");
  lines.push(serveOpenApi ? `  controllers: [...controllers, { name: "qalaOpenapi", prefix: "/openapi.json", controller: ${OPENAPI_EXPORT} }],` : "  controllers,");
  // Generated providers first: app/providers.ts registers after them, so its overrides win.
  if (hasGeneratedProviders) lines.push(hasProviders ? "  providers: [...generatedProviders, ...providers]," : "  providers: generatedProviders,");
  else if (hasProviders) lines.push("  providers,");
  if (hasKernel) lines.push("  middleware: kernel.middleware,", "  onError: kernel.onError,", "  exposeErrors: kernel.exposeErrors,");
  // `locale: "az"` in the kernel sets the default language of framework messages.
  if (hasKernel && /\blocale\s*[:,}]/.test(kernelSource)) lines.push("  locale: kernel.locale,");
  if (hasAuthenticate) lines.push("  authenticate,");
  lines.push("});", "");
  // Event handlers and audit/realtime sinks resolve services from the app's container.
  if (bindsEvents) lines.push("bindEvents(app.container);", "");
  if (hasOnShutdown) lines.push("app.onShutdown(() => onShutdown(app));", "");
  // Port: config/app.ts's `config.port`, else the typed env's PORT (.env.example), else $PORT or 3000.
  const port = hasConfig ? "config.port" : envPort ? "env.PORT" : 'Number(process.env.PORT ?? "3000")';
  const serveCall = hasServeOptions ? `serve(app, { port: ${port}, ...serveOptions })` : `serve(app, { port: ${port} })`;
  lines.push(hasOnStart ? `${serveCall}.then(() => onStart(app, { primary: !isWorker() }));` : `${serveCall};`, "");
  return lines.join("\n");
}

/**
 * `.qala/app.gen.ts`: the same options the generated main passes to createApp, exported for tests
 * (`testApp({ ...appOptions })`) so an in-process test app is wired exactly like the real one.
 * Derived from renderMain so the two can never drift. Imported by tests only, never by main.ts.
 */
export function renderAppOptions(root: string, hasModels = false, hasGeneratedProviders = false): string {
  const main = renderMain(root, hasModels, hasGeneratedProviders);
  const out: string[] = [];
  let bindsEvents = false;
  for (const line of main.split("\n")) {
    if (/^import \{ createApp(, isWorker)?, serve \} from "@qala\/core";$/.test(line)) {
      out.push('import type { App, AppOptions } from "@qala/core";');
      continue;
    }
    if (line.startsWith("import { env }") || line.startsWith("import { config }")) continue;
    if (line.startsWith("import { kernel")) {
      out.push(line.replace(/import \{ kernel[^}]*\}/, "import { kernel }"));
      continue;
    }
    if (line === "const app = createApp({") {
      out.push("export const appOptions: AppOptions = {");
      continue;
    }
    if (line === "});") {
      out.push("};");
      continue;
    }
    if (line === "bindEvents(app.container);") {
      bindsEvents = true;
      continue;
    }
    if (line.startsWith("serve(") || line.startsWith("app.onShutdown(")) continue;
    out.push(line);
  }
  out.push("/** Call on an app built from appOptions (testApp does this for you when passed `setup`). */");
  out.push(bindsEvents ? "export function setup(app: App): void {\n  bindEvents(app.container);\n}" : "export function setup(_app: App): void {}");
  out.push("");
  return out.join("\n").replace(/\n{3,}/g, "\n\n");
}

/**
 * Scans controllers and models and (re)writes `.qala/routes.gen.ts`, `.qala/api.ts`, `.qala/main.ts`
 * and, when the app has models, `.qala/models.gen.ts` (typed row decoders compiled statically by scriptc).
 */
export function generate(root: string): Generated {
  const controllers = scanControllers(root);
  const { models, skipped } = scanModels(root);
  // Providers from constructor parameter types; the routes' controllers are the classes that must be buildable.
  const di = generateProviders(root, {
    classControllers: controllers.filter((c) => c.kind === "class").map((c) => ({ file: c.file, name: c.exportName })),
    functionControllerFiles: controllers.filter((c) => c.kind === "function").map((c) => c.file),
  });
  assertProviders(di);
  const dir = join(root, LAYOUT.generated);
  const written: string[] = [];
  const hasModels = models.length > 0;
  const hasGeneratedProviders = di.source !== null;
  const files: [string, string][] = [
    ["routes.gen.ts", renderRoutes(root, controllers)],
    ["api.ts", renderApi(root, controllers)],
  ];
  if (hasModels) files.push(["models.gen.ts", renderModels(root, models)]);
  if (di.source !== null) files.push([PROVIDERS_GEN, di.source]);
  const authTypes = hasAppUser(root);
  if (authTypes) files.push([AUTH_GEN, renderAuthTypes(root)]);
  files.push(["main.ts", renderMain(root, hasModels, hasGeneratedProviders)]);
  files.push(["app.gen.ts", renderAppOptions(root, hasModels, hasGeneratedProviders)]);
  for (const [name, content] of files) if (writeIfChanged(join(dir, name), content)) written.push(`${LAYOUT.generated}/${name}`);
  const stale = join(dir, "models.gen.ts");
  if (!hasModels && existsSync(stale)) rmSync(stale);
  const staleAuth = join(dir, AUTH_GEN);
  if (!authTypes && existsSync(staleAuth)) rmSync(staleAuth);
  const staleProviders = join(dir, PROVIDERS_GEN);
  if (!hasGeneratedProviders && existsSync(staleProviders)) rmSync(staleProviders);
  // Compiled queries (SQL + typed decoders) from app/infrastructure/queries/*.query.ts.
  const envFile = generateEnv(root);
  if (envFile !== null) written.push(envFile);
  const queries = generateQueries(root);
  if (queries.written) written.push(`${LAYOUT.generated}/${QUERIES_GEN}`);
  // Last: it loads the app, which needs every other generated file.
  written.push(...generateOpenApiFiles(root));
  return { controllers, models, skippedModels: skipped, written, queries: queries.count, providers: di.count, diWarnings: di.warnings };
}

const AUTH_GEN = "auth.gen.ts";

/** `.qala/openapi.gen.ts`: the document as a string constant and the controller serving it (opt-in). */
export const OPENAPI_GEN = "openapi.gen.ts";
const OPENAPI_EXPORT = "QalaOpenapiController";

/** The module serving a pre-generated document: a plain string reply, so it compiles natively. */
export function renderOpenApiModule(json: string): string {
  return [
    HEADER,
    'import { action, controller, Reply } from "@qala/core";',
    "",
    `export const openapiJson: string = ${JSON.stringify(json)};`,
    "",
    '/** GET /openapi.json (enabled by `"qala": { "openapi": { "serve": true } }` in package.json). */',
    `export const ${OPENAPI_EXPORT} = controller({}, () => ({`,
    '  index: action({}, () => new Reply(200, openapiJson, { "content-type": "application/json; charset=utf-8" })),',
    "}));",
    "",
  ].join("\n");
}

/**
 * Writes the app's OpenAPI document to `out` (JSON, or YAML with `yaml`) by loading the generated app in a
 * separate Bun process (`@qala/openapi/run`), so app modules never load into the CLI.
 */
export function writeOpenApi(root: string, out: string, yaml = false): void {
  const runner = Bun.resolveSync("@qala/openapi/run", import.meta.dir);
  const run = Bun.spawnSync([process.execPath, runner, root, out, ...(yaml ? ["--yaml"] : [])], { cwd: root, stdout: "pipe", stderr: "pipe" });
  if (run.exitCode !== 0) throw new CliError(`OpenAPI generation failed:\n${run.stderr.toString()}${run.stdout.toString()}`);
}

/**
 * When package.json opts in (`"qala": { "openapi": true }`), writes `.qala/openapi.json` and, with
 * `{ "serve": true }`, `.qala/openapi.gen.ts` (served at /openapi.json). Returns the files written.
 */
function generateOpenApiFiles(root: string): string[] {
  const config = openApiConfig(root);
  const dir = join(root, LAYOUT.generated);
  const genFile = join(dir, OPENAPI_GEN);
  const jsonFile = join(dir, "openapi.json");
  const serve = config !== null && config.serve === true;
  if (!serve && existsSync(genFile)) rmSync(genFile);
  if (config === null) return [];
  // The app imports the generated module, so it must exist before the app can be loaded to describe itself.
  if (serve && !existsSync(genFile)) writeIfChanged(genFile, renderOpenApiModule("{}"));
  const tmp = mkdtempSync(join(tmpdir(), "qala-openapi-"));
  try {
    const out = join(tmp, "openapi.json");
    writeOpenApi(root, out);
    const json = readFileSync(out, "utf8");
    const written: string[] = [];
    if (writeIfChanged(jsonFile, json)) written.push(`${LAYOUT.generated}/openapi.json`);
    if (serve && writeIfChanged(genFile, renderOpenApiModule(JSON.stringify(JSON.parse(json))))) written.push(`${LAYOUT.generated}/${OPENAPI_GEN}`);
    return written;
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

/** Whether app/auth.ts exports an `AppUser` type (then `.qala/auth.gen.ts` types `user` in handlers). */
export function hasAppUser(root: string): boolean {
  const file = join(root, "app/auth.ts");
  return existsSync(file) && /export\s+(type|interface)\s+AppUser\b/.test(readFileSync(file, "utf8"));
}

/** Declaration merging that types `user` (and `currentUser`/`requireUser`) as the app's `AppUser`. */
export function renderAuthTypes(root: string): string {
  const dir = join(root, LAYOUT.generated);
  return [
    HEADER,
    `import type { AppUser } from "${importPath(dir, join(root, "app/auth.ts"))}";`,
    "",
    'declare module "@qala/core" {',
    "  interface AuthTypes {",
    "    user: AppUser;",
    "  }",
    "}",
    "",
    "export {};",
    "",
  ].join("\n");
}

/** `app/events/*.ts` (sorted): modules that register model event handlers with `on(...)`. */
function eventModules(root: string): string[] {
  const dir = join(root, "app/events");
  if (!existsSync(dir)) return [];
  const files: string[] = [];
  for (const name of readdirSync(dir).sort()) {
    if (name.endsWith(".ts") && !name.endsWith(".test.ts") && !name.endsWith(".d.ts")) files.push(join(dir, name));
  }
  return files;
}
