import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { pathToFileURL } from "node:url";
import { loadCore } from "./run";
import { CliError, color, LAYOUT, walk } from "./util";

/**
 * `qala migrate:make <name>`: compares the app's models with the live database and writes the SQL that
 * makes the database match (database/migrations/NNNN_<name>.sql). It never drops data: removals are
 * written as comments for a human to review.
 */

/** One model column as the database should have it. */
export type ColumnSpec = {
  name: string;
  /** Canonical SQL type (as `format_type` prints it). */
  type: string;
  /** The type as written in CREATE/ALTER statements. */
  declared: string;
  nullable: boolean;
  defaultExpr: string | null;
  identity: boolean;
  primary: boolean;
  unique: boolean;
  indexed: boolean;
  refTable: string;
  refColumn: string;
  onDelete: string;
};

export type TableSpec = { table: string; columns: ColumnSpec[] };

/** What the database has (public schema). */
export type DbColumn = { type: string; nullable: boolean; defaultExpr: string | null; identity: boolean };
export type DbTable = {
  columns: Map<string, DbColumn>;
  primary: string[];
  /** Single-column unique constraints/indexes. */
  unique: Set<string>;
  /** Single-column non-unique indexes. */
  indexed: Set<string>;
  /** Single-column foreign keys: column → "table.column ondelete". */
  foreign: Map<string, string>;
};
export type DbSnapshot = Map<string, DbTable>;

type ModelLike = {
  table: string;
  keys: string[];
  columns: string[];
  kinds: string[];
  primaryKey: string;
  nullable: boolean[];
  fields: { column: { isPrimary: boolean; defaultExpr: string | null; isUnique: boolean; isIndexed: boolean; refTable: string; refColumn: string; onDelete: string; sqlType: string | null; isNullable: boolean } }[];
};

const KIND_TYPES: Record<string, string> = {
  uuid: "uuid",
  string: "text",
  email: "text",
  enum: "text",
  literal: "text",
  datetime: "timestamptz",
  integer: "integer",
  number: "double precision",
  boolean: "boolean",
  unknown: "jsonb",
  array: "jsonb",
  object: "jsonb",
};

/** Short SQL type names → the form `format_type` reports, so model and database types compare equal. */
export function canonicalType(type: string): string {
  const t = type.trim().toLowerCase().replace(/\s+/g, " ");
  const varchar = /^(?:varchar|character varying)\s*\((\d+)\)$/.exec(t);
  if (varchar !== null) return `character varying(${varchar[1]})`;
  const numeric = /^(?:numeric|decimal)\s*\((\d+)\s*,\s*(\d+)\)$/.exec(t);
  if (numeric !== null) return `numeric(${numeric[1]},${numeric[2]})`;
  const aliases: Record<string, string> = {
    timestamptz: "timestamp with time zone",
    timestamp: "timestamp without time zone",
    int: "integer",
    int4: "integer",
    int8: "bigint",
    int2: "smallint",
    float8: "double precision",
    float4: "real",
    bool: "boolean",
    varchar: "character varying",
    decimal: "numeric",
  };
  return aliases[t] ?? t;
}

function isModel(value: unknown): value is ModelLike {
  if (typeof value !== "object" || value === null) return false;
  const v = value as Record<string, unknown>;
  return typeof v["table"] === "string" && Array.isArray(v["keys"]) && Array.isArray(v["columns"]) && Array.isArray(v["fields"]) && typeof v["primaryKey"] === "string" && Array.isArray(v["nullable"]);
}

/** The columns a model wants. */
export function tableSpec(model: ModelLike): TableSpec {
  const columns: ColumnSpec[] = [];
  for (let i = 0; i < model.keys.length; i++) {
    const field = model.fields[i]!;
    const c = field.column;
    const kind = model.kinds[i]!;
    const primary = model.keys[i] === model.primaryKey;
    const declared = c.sqlType ?? KIND_TYPES[kind] ?? "text";
    const identity = primary && c.defaultExpr === null && (kind === "integer" || /^(int|integer|bigint|int8|smallint)$/i.test(declared));
    columns.push({
      name: model.columns[i]!,
      type: canonicalType(declared),
      declared,
      nullable: !primary && (model.nullable[i] === true || c.isNullable),
      defaultExpr: c.defaultExpr,
      identity,
      primary,
      unique: c.isUnique,
      indexed: c.isIndexed,
      refTable: c.refTable,
      refColumn: c.refColumn,
      onDelete: c.onDelete,
    });
  }
  return { table: model.table, columns };
}

function q(name: string): string {
  return `"${name.replace(/"/g, '""')}"`;
}

function columnSql(c: ColumnSpec): string {
  let sql = `${q(c.name)} ${c.declared}`;
  if (c.identity) sql += " generated by default as identity";
  if (!c.nullable) sql += " not null";
  if (c.defaultExpr !== null && !c.identity) sql += ` default ${c.defaultExpr}`;
  return sql;
}

/** Postgres prints defaults with casts (`'todo'::text`, `now()`); compare without them. */
export function normalizeDefault(expr: string | null): string | null {
  if (expr === null) return null;
  let e = expr.trim();
  for (;;) {
    const m = /^(.*)::[a-z_ ]+(\[\])?(\([0-9, ]+\))?$/i.exec(e);
    if (m === null || m[1] === undefined) break;
    e = m[1].trim();
    if (e.startsWith("(") && e.endsWith(")")) e = e.slice(1, -1).trim();
  }
  if (/^current_timestamp$/i.test(e)) e = "now()";
  return e.toLowerCase();
}

function fkTarget(c: ColumnSpec): string {
  return `${c.refTable}.${c.refColumn} ${c.onDelete === "" ? "no action" : c.onDelete}`;
}

function addForeignKey(table: string, c: ColumnSpec): string {
  const onDelete = c.onDelete === "" ? "" : ` on delete ${c.onDelete}`;
  return `alter table ${q(table)} add constraint ${q(`${table}_${c.name}_fkey`)} foreign key (${q(c.name)}) references ${q(c.refTable)} (${q(c.refColumn)})${onDelete};`;
}

export type MigrationPlan = {
  /** SQL statements to run, in order. */
  statements: string[];
  /** Comments: removals and risky changes left for a human. */
  notes: string[];
};

/** Tables Qala itself manages; never reported as unknown. */
const INTERNAL_TABLES = new Set(["qala_migrations"]);

/** The SQL that makes `db` match `wanted`. Pure: no database access. */
export function diffSchema(wanted: TableSpec[], db: DbSnapshot): MigrationPlan {
  const statements: string[] = [];
  const notes: string[] = [];
  const later: string[] = [];
  const names = new Set<string>();
  for (const spec of wanted) {
    names.add(spec.table);
    const existing = db.get(spec.table);
    if (existing === undefined) {
      const lines = spec.columns.map((c) => `  ${columnSql(c)}`);
      const pk = spec.columns.filter((c) => c.primary).map((c) => q(c.name));
      if (pk.length > 0) lines.push(`  primary key (${pk.join(", ")})`);
      statements.push(`create table ${q(spec.table)} (\n${lines.join(",\n")}\n);`);
      for (const c of spec.columns) {
        if (c.unique && !c.primary) later.push(`alter table ${q(spec.table)} add constraint ${q(`${spec.table}_${c.name}_key`)} unique (${q(c.name)});`);
        if (c.indexed) later.push(`create index ${q(`${spec.table}_${c.name}_idx`)} on ${q(spec.table)} (${q(c.name)});`);
        if (c.refTable !== "") later.push(addForeignKey(spec.table, c));
      }
      continue;
    }
    for (const c of spec.columns) {
      const have = existing.columns.get(c.name);
      if (have === undefined) {
        if (!c.nullable && c.defaultExpr === null && !c.identity) {
          statements.push(`alter table ${q(spec.table)} add column ${columnSql({ ...c, nullable: true })};`);
          notes.push(`existing rows of ${spec.table} have no ${c.name}: backfill it, then run\n--   alter table ${q(spec.table)} alter column ${q(c.name)} set not null;`);
        } else {
          statements.push(`alter table ${q(spec.table)} add column ${columnSql(c)};`);
        }
      } else {
        if (have.type !== c.type) {
          statements.push(`alter table ${q(spec.table)} alter column ${q(c.name)} type ${c.declared} using ${q(c.name)}::${c.declared}; -- review: changes the column type (was ${have.type})`);
        }
        if (have.nullable && !c.nullable) statements.push(`alter table ${q(spec.table)} alter column ${q(c.name)} set not null;`);
        if (!have.nullable && c.nullable) statements.push(`alter table ${q(spec.table)} alter column ${q(c.name)} drop not null;`);
        if (!c.identity && !have.identity && normalizeDefault(have.defaultExpr) !== normalizeDefault(c.defaultExpr)) {
          statements.push(
            c.defaultExpr === null
              ? `alter table ${q(spec.table)} alter column ${q(c.name)} drop default;`
              : `alter table ${q(spec.table)} alter column ${q(c.name)} set default ${c.defaultExpr};`,
          );
        }
      }
      if (c.unique && !c.primary && !existing.unique.has(c.name)) later.push(`alter table ${q(spec.table)} add constraint ${q(`${spec.table}_${c.name}_key`)} unique (${q(c.name)});`);
      if (c.indexed && !existing.indexed.has(c.name) && !existing.unique.has(c.name)) later.push(`create index ${q(`${spec.table}_${c.name}_idx`)} on ${q(spec.table)} (${q(c.name)});`);
      if (c.refTable !== "") {
        const fk = existing.foreign.get(c.name);
        if (fk === undefined) later.push(addForeignKey(spec.table, c));
        else if (fk !== fkTarget(c)) notes.push(`${spec.table}.${c.name} references ${fk} in the database but ${fkTarget(c)} in the model; to change it:\n--   alter table ${q(spec.table)} drop constraint ${q(`${spec.table}_${c.name}_fkey`)};\n--   ${addForeignKey(spec.table, c)}`);
      }
    }
    const wantedPk = spec.columns.filter((c) => c.primary).map((c) => c.name);
    if (existing.primary.length > 0 && existing.primary.join(",") !== wantedPk.join(",")) notes.push(`${spec.table}: primary key is (${existing.primary.join(", ")}) in the database but (${wantedPk.join(", ")}) in the model`);
    const wantedColumns = new Set(spec.columns.map((c) => c.name));
    for (const name of existing.columns.keys()) {
      if (!wantedColumns.has(name)) notes.push(`${spec.table}.${name} is not in the model; to remove it:\n--   alter table ${q(spec.table)} drop column ${q(name)};`);
    }
  }
  for (const table of db.keys()) {
    if (!names.has(table) && !INTERNAL_TABLES.has(table)) notes.push(`table ${table} has no model; to remove it:\n--   drop table ${q(table)};`);
  }
  return { statements: statements.concat(later), notes };
}

type Queryable = { query(sql: string, params?: unknown[]): Promise<Record<string, unknown>[]>; close(): void };

const SNAPSHOT_COLUMNS = `
select c.relname as table, a.attname as column, format_type(a.atttypid, a.atttypmod) as type,
       not a.attnotnull as nullable, pg_get_expr(d.adbin, d.adrelid) as default_expr, a.attidentity <> '' as identity
from pg_attribute a
join pg_class c on c.oid = a.attrelid and c.relkind = 'r'
join pg_namespace n on n.oid = c.relnamespace and n.nspname = 'public'
left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
where a.attnum > 0 and not a.attisdropped
order by c.relname, a.attnum`;

const SNAPSHOT_INDEXES = `
select c.relname as table, i.indisprimary as primary, i.indisunique as unique, i.indnatts as columns,
       (select array_to_string(array_agg(a.attname order by k.ord), ',')
          from unnest(i.indkey) with ordinality as k(attnum, ord)
          join pg_attribute a on a.attrelid = c.oid and a.attnum = k.attnum) as names
from pg_index i
join pg_class c on c.oid = i.indrelid
join pg_namespace n on n.oid = c.relnamespace and n.nspname = 'public'
where i.indexprs is null and i.indpred is null`;

const SNAPSHOT_FOREIGN = `
select c.relname as table, a.attname as column, rc.relname as ref_table, ra.attname as ref_column, con.confdeltype as on_delete
from pg_constraint con
join pg_class c on c.oid = con.conrelid
join pg_namespace n on n.oid = c.relnamespace and n.nspname = 'public'
join pg_class rc on rc.oid = con.confrelid
join pg_attribute a on a.attrelid = con.conrelid and a.attnum = con.conkey[1]
join pg_attribute ra on ra.attrelid = con.confrelid and ra.attnum = con.confkey[1]
where con.contype = 'f' and array_length(con.conkey, 1) = 1`;

const ON_DELETE: Record<string, string> = { a: "no action", r: "restrict", c: "cascade", n: "set null", d: "set default" };

/** Reads the public schema's tables, columns, keys and indexes. */
export async function readSnapshot(db: Queryable): Promise<DbSnapshot> {
  const snapshot: DbSnapshot = new Map();
  const table = (name: string): DbTable => {
    let t = snapshot.get(name);
    if (t === undefined) {
      t = { columns: new Map(), primary: [], unique: new Set(), indexed: new Set(), foreign: new Map() };
      snapshot.set(name, t);
    }
    return t;
  };
  for (const row of await db.query(SNAPSHOT_COLUMNS)) {
    table(String(row["table"])).columns.set(String(row["column"]), {
      type: canonicalType(String(row["type"])),
      nullable: row["nullable"] === true,
      defaultExpr: row["default_expr"] === null ? null : String(row["default_expr"]),
      identity: row["identity"] === true,
    });
  }
  for (const row of await db.query(SNAPSHOT_INDEXES)) {
    const t = table(String(row["table"]));
    const cols = String(row["names"] ?? "").split(",").filter((s) => s !== "");
    if (row["primary"] === true) t.primary = cols;
    else if (cols.length === 1 && row["unique"] === true) t.unique.add(cols[0]!);
    else if (cols.length === 1) t.indexed.add(cols[0]!);
  }
  for (const row of await db.query(SNAPSHOT_FOREIGN)) {
    table(String(row["table"])).foreign.set(String(row["column"]), `${String(row["ref_table"])}.${String(row["ref_column"])} ${ON_DELETE[String(row["on_delete"])] ?? "no action"}`);
  }
  return snapshot;
}

/** Imports the app's model modules and returns every exported model. */
export async function loadModels(root: string): Promise<ModelLike[]> {
  const files = walk(join(root, LAYOUT.app), (f) => f.endsWith(".ts") && !f.endsWith(".d.ts") && /\bmodel\s*\(/.test(readFileSync(f, "utf8")));
  const models: ModelLike[] = [];
  const seen = new Set<string>();
  for (const file of files) {
    const mod = (await import(pathToFileURL(file).href)) as Record<string, unknown>;
    for (const value of Object.values(mod)) {
      if (!isModel(value) || seen.has(value.table)) continue;
      seen.add(value.table);
      models.push(value);
    }
  }
  return models;
}

/** The SQL file text for a plan. */
export function renderMigration(name: string, plan: MigrationPlan): string {
  const lines = [`-- ${name}: generated by \`qala migrate:make\` from the models. Review before applying.`, ""];
  for (const s of plan.statements) lines.push(s, "");
  if (plan.notes.length > 0) {
    lines.push("-- Not applied automatically (review):");
    for (const n of plan.notes) lines.push(`-- ${n}`);
    lines.push("");
  }
  return lines.join("\n");
}

/** Next migration file name: 0001_name.sql, 0002_name.sql, ... */
export function nextMigrationName(dir: string, name: string): string {
  const slug = name.trim().toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "") || "migration";
  let max = 0;
  if (existsSync(dir)) {
    for (const f of readdirSync(dir)) {
      const m = /^(\d+)_/.exec(f);
      if (m !== null) max = Math.max(max, Number(m[1]));
    }
  }
  return `${String(max + 1).padStart(4, "0")}_${slug}.sql`;
}

/** `qala migrate:make <name> [--print]`. */
export async function migrateMakeCommand(root: string, name: string, options: { print?: boolean } = {}): Promise<number> {
  const configFile = join(root, LAYOUT.config);
  if (!existsSync(configFile)) throw new CliError(`${LAYOUT.config} is missing; it must export config with databaseUrl`);
  const previous = process.cwd();
  process.chdir(root);
  try {
    const { config } = (await import(pathToFileURL(configFile).href)) as { config?: { databaseUrl?: string } };
    if (config === undefined || typeof config.databaseUrl !== "string") throw new CliError(`${LAYOUT.config} must export \`config\` with a \`databaseUrl\` string`);
    const models = await loadModels(root);
    if (models.length === 0) throw new CliError("No models found under app/ (export const X = model(...))");
    const core = (await loadCore(root)) as unknown as { Database: new (url: string) => Queryable };
    const db = new core.Database(config.databaseUrl);
    let plan: MigrationPlan;
    try {
      plan = diffSchema(models.map(tableSpec), await readSnapshot(db));
    } finally {
      db.close();
    }
    if (plan.statements.length === 0) {
      console.log(color.green("✓ The database already matches the models."));
      for (const n of plan.notes) console.log(color.dim(`  note: ${n.split("\n")[0]}`));
      return 0;
    }
    const dir = join(root, LAYOUT.migrations);
    const file = nextMigrationName(dir, name);
    const text = renderMigration(file.replace(/\.sql$/, ""), plan);
    if (options.print === true) {
      console.log(text);
      return 0;
    }
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, file), text);
    console.log(`${color.green("✓")} ${relative(root, join(dir, file))}  ${plan.statements.length} statement(s)${plan.notes.length > 0 ? `, ${plan.notes.length} note(s) to review` : ""}`);
    console.log(color.dim("  Review it, then run: qala migrate"));
    return 0;
  } finally {
    process.chdir(previous);
  }
}
