import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { Database, model, t } from "../../core/src/index";
import { canonicalType, diffSchema, nextMigrationName, normalizeDefault, readSnapshot, renderMigration, tableSpec, type DbSnapshot } from "../src/migrate-make";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const URL = process.env.QALA_TEST_DATABASE_URL ?? "postgres://qala:qala@localhost:5432/qala_test";

const Board = model("t_mm_boards", {
  id: t.uuid().primary(),
  name: t.string().unique(),
});
const Card = model("t_mm_cards", {
  id: t.uuid().primary(),
  boardId: t.uuid().references(Board, { onDelete: "cascade" }),
  title: t.string().type("varchar(200)"),
  done: t.boolean().default(false),
  position: t.integer().default(0).index(),
  note: t.string().nullable(),
  meta: t.unknown().nullable(),
  createdAt: t.datetime().now(),
});
const Counter = model("t_mm_counters", { id: t.integer().primary(), hits: t.integer().default(0) });

function only(snapshot: DbSnapshot, prefix: string): DbSnapshot {
  const out: DbSnapshot = new Map();
  for (const [k, v] of snapshot) if (k.startsWith(prefix)) out.set(k, v);
  return out;
}

describe("diffSchema (pure)", () => {
  test("creates missing tables, then constraints and indexes", () => {
    const plan = diffSchema([tableSpec(Board), tableSpec(Card)], new Map());
    expect(plan.notes).toEqual([]);
    expect(plan.statements[0]).toBe('create table "t_mm_boards" (\n  "id" uuid not null default gen_random_uuid(),\n  "name" text not null,\n  primary key ("id")\n);');
    expect(plan.statements[1]).toContain('"title" varchar(200) not null');
    expect(plan.statements[1]).toContain('"note" text,');
    expect(plan.statements[1]).toContain('"meta" jsonb,');
    expect(plan.statements[1]).toContain('"created_at" timestamptz not null default now()');
    expect(plan.statements.slice(2)).toEqual([
      'alter table "t_mm_boards" add constraint "t_mm_boards_name_key" unique ("name");',
      'alter table "t_mm_cards" add constraint "t_mm_cards_board_id_fkey" foreign key ("board_id") references "t_mm_boards" ("id") on delete cascade;',
      'create index "t_mm_cards_position_idx" on "t_mm_cards" ("position");',
    ]);
  });

  test("integer primary keys are identity columns", () => {
    expect(diffSchema([tableSpec(Counter)], new Map()).statements[0]).toContain('"id" integer generated by default as identity not null');
  });

  test("helpers", () => {
    expect(canonicalType("timestamptz")).toBe("timestamp with time zone");
    expect(canonicalType("varchar(200)")).toBe("character varying(200)");
    expect(normalizeDefault("'todo'::text")).toBe("'todo'");
    expect(normalizeDefault("CURRENT_TIMESTAMP")).toBe("now()");
    expect(normalizeDefault("0")).toBe("0");
    const dir = mkdtempSync(join(tmpdir(), "qala-mm-"));
    expect(nextMigrationName(dir, "Add Cards!")).toBe("0001_add_cards.sql");
    writeFileSync(join(dir, "0007_x.sql"), "");
    expect(nextMigrationName(dir, "next")).toBe("0008_next.sql");
  });
});

describe("migrate:make against a live database", () => {
  const db = new Database(URL, { max: 2 });
  const drop = async () => {
    await db.execute("drop table if exists t_mm_cards");
    await db.execute("drop table if exists t_mm_boards");
    await db.execute("drop table if exists t_mm_counters");
  };
  beforeAll(drop);
  afterAll(async () => {
    await drop();
    db.close();
  });

  test("create from nothing, apply, then nothing left to do", async () => {
    const wanted = [tableSpec(Board), tableSpec(Card), tableSpec(Counter)];
    const plan = diffSchema(wanted, only(await readSnapshot(db), "t_mm_"));
    expect(plan.statements.length).toBe(6);
    for (const s of plan.statements) await db.execute(s);
    const again = diffSchema(wanted, only(await readSnapshot(db), "t_mm_"));
    expect(again).toEqual({ statements: [], notes: [] });
    const inserted = await db.table(Card).insert({ boardId: (await db.table(Board).insert({ name: "b" })).id, title: "c" });
    expect(inserted.done).toBe(false);
  });

  test("changes: new column, default, nullability, extra column only as a comment", async () => {
    await db.execute("alter table t_mm_cards drop column note");
    await db.execute("alter table t_mm_cards alter column done set default true");
    await db.execute("alter table t_mm_cards alter column title drop not null");
    await db.execute("alter table t_mm_cards add column legacy text");
    await db.execute("drop index t_mm_cards_position_idx");
    const plan = diffSchema([tableSpec(Board), tableSpec(Card), tableSpec(Counter)], only(await readSnapshot(db), "t_mm_"));
    expect(plan.statements).toEqual([
      'alter table "t_mm_cards" alter column "title" set not null;',
      'alter table "t_mm_cards" alter column "done" set default false;',
      'alter table "t_mm_cards" add column "note" text;',
      'create index "t_mm_cards_position_idx" on "t_mm_cards" ("position");',
    ]);
    expect(plan.notes).toEqual(['t_mm_cards.legacy is not in the model; to remove it:\n--   alter table "t_mm_cards" drop column "legacy";']);
    const text = renderMigration("0002_cards", plan);
    expect(text).toContain('--   alter table "t_mm_cards" drop column "legacy";');
    expect(text.endsWith("-- migrate:down\n-- SQL that undoes the statements above (run by qala migrate:rollback).\n")).toBe(true);
    for (const s of plan.statements) await db.execute(s);
    expect(diffSchema([tableSpec(Board), tableSpec(Card), tableSpec(Counter)], only(await readSnapshot(db), "t_mm_")).statements).toEqual([]);
  });

  test("a new NOT NULL column without a default is added nullable, with a backfill note", async () => {
    const Wider = model("t_mm_counters", { id: t.integer().primary(), hits: t.integer().default(0), label: t.string() });
    const plan = diffSchema([tableSpec(Wider)], only(await readSnapshot(db), "t_mm_counters"));
    expect(plan.statements).toEqual(['alter table "t_mm_counters" add column "label" text;']);
    expect(plan.notes[0]).toContain("backfill");
  });
});
