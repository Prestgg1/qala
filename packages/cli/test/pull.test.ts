import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { Database } from "../../core/src/index";
import { pullCommand } from "../src/pull";

const REPO = resolve(import.meta.dir, "../../..");
const CORE = join(REPO, "packages/core/src/index.ts");
const TSC = join(REPO, "node_modules/.bin/tsc");
const URL = process.env.QALA_TEST_DATABASE_URL ?? "postgres://qala:qala@localhost:5432/qala_test";

let db: Database;
let reachable = true;
const out = mkdtempSync(join(tmpdir(), "qala-pull-"));

const DROP = ["drop table if exists t_pull_members", "drop table if exists t_pull_orders", "drop table if exists t_pull_users", "drop table if exists t_pull_links", "drop type if exists t_pull_role"];

beforeAll(async () => {
  try {
    db = new Database(URL);
    for (const s of DROP) await db.execute(s);
    await db.execute("create type t_pull_role as enum ('admin', 'member', 'it''s')");
    await db.execute(`create table t_pull_users (
      id uuid primary key, email varchar(200) not null, display_name text, age int4, visits int8 not null default 0,
      balance numeric(12,2), score float8, active bool not null default true, role t_pull_role not null default 'member',
      created_at timestamptz not null default now(), born date, meta jsonb, tags text[], "userID" text, line_2 text)`);
    await db.execute("create table t_pull_orders (id uuid primary key, user_id uuid not null references t_pull_users(id), total numeric not null)");
    await db.execute("create table t_pull_members (org_id int4, user_id int4, note text, primary key (org_id, user_id))");
    await db.execute("create table t_pull_links (a text, b text)");
  } catch {
    reachable = false;
  }
});

afterAll(async () => {
  if (reachable) {
    for (const s of DROP) await db.execute(s);
  }
  db?.close();
  rmSync(out, { recursive: true, force: true });
});

describe("qala db:pull", () => {
  test("generates models, skips unmappable columns and tables", async () => {
    if (!reachable) return console.warn("postgres not reachable; skipping");
    const log = console.log;
    console.log = () => {};
    try {
      expect(await pullCommand(REPO, { url: URL, tables: "t_pull_users,t_pull_orders,t_pull_members,t_pull_links", out })).toBe(0);
    } finally {
      console.log = log;
    }
    expect(readdirSync(out).sort()).toEqual(["index.ts", "t-pull-member.model.ts", "t-pull-order.model.ts", "t-pull-user.model.ts"]);

    const users = readFileSync(join(out, "t-pull-user.model.ts"), "utf8");
    expect(users).toStartWith("// generated by qala db:pull — edit freely\n");
    expect(users).toContain('export const TPullUser = model("t_pull_users", {');
    expect(users).toContain("export type TPullUser = InferModel<typeof TPullUser>;");
    expect(users).toContain("  id: t.uuid(),");
    expect(users).toContain("  email: t.string(),");
    expect(users).toContain("  displayName: t.nullable(t.string()),");
    expect(users).toContain("  age: t.nullable(t.integer()),");
    expect(users).toContain("  visits: t.string(), // bigint as string (precision); default 0");
    expect(users).toContain("  balance: t.nullable(t.string()), // numeric as string (precision)");
    expect(users).toContain("  score: t.nullable(t.number()),");
    expect(users).toContain("  active: t.boolean(), // default true");
    expect(users).toContain('  role: t.enum(["admin", "member", "it\'s"]), // default');
    expect(users).toContain("  createdAt: t.datetime(), // default now()");
    expect(users).toContain("  born: t.nullable(t.datetime()),");
    expect(users).toContain("  meta: t.nullable(t.unknown()), // jsonb kept as unknown");
    expect(users).toContain("  tags: t.nullable(t.unknown()), // array (text[]) kept as unknown");
    expect(users).not.toContain("userID");
    expect(users).not.toContain("line2");
    // columns keep the table's ordinal order
    expect(users.indexOf("id:")).toBeLessThan(users.indexOf("email:"));
    expect(users.indexOf("email:")).toBeLessThan(users.indexOf("createdAt:"));

    const orders = readFileSync(join(out, "t-pull-order.model.ts"), "utf8");
    expect(orders).toContain("  userId: t.uuid(), // references t_pull_users.id");

    const members = readFileSync(join(out, "t-pull-member.model.ts"), "utf8");
    expect(members).toContain('}, { primaryKey: "orgId" });');
    expect(members).toContain("composite primary key (org_id, user_id)");

    // no primary key and no id: table skipped (no file, not in the index)
    expect(readFileSync(join(out, "index.ts"), "utf8")).not.toContain("t-pull-link");
    expect(readFileSync(join(out, "index.ts"), "utf8")).toContain('export { TPullUser } from "./t-pull-user.model";');
  });

  test("is deterministic and the generated files typecheck", () => {
    if (!reachable) return;
    const dir = mkdtempSync(join(tmpdir(), "qala-pull-tc-"));
    try {
      mkdirSync(join(dir, "app"), { recursive: true });
      for (const f of readdirSync(out)) writeFileSync(join(dir, "app", f), readFileSync(join(out, f)));
      writeFileSync(
        join(dir, "check.ts"),
        'import { TPullUser, TPullMember } from "./app/index";\nconst u: TPullUser = { id: "x", email: "e", displayName: null, age: null, visits: "1", balance: null, score: null, active: true, role: "admin", createdAt: "d", born: null, meta: {}, tags: [] };\nconst m: TPullMember = { orgId: 1, userId: 2, note: null };\nvoid u; void m;\n// @ts-expect-error role is an enum\nconst bad: TPullUser["role"] = "nope";\nvoid bad;\n',
      );
      writeFileSync(
        join(dir, "tsconfig.json"),
        JSON.stringify({
          compilerOptions: { target: "ES2022", module: "ESNext", moduleResolution: "bundler", strict: true, noUncheckedIndexedAccess: true, skipLibCheck: true, noEmit: true, types: ["node", "bun"], typeRoots: [join(REPO, "node_modules/@types")], paths: { "@qala/core": [CORE] } },
          include: ["app", "check.ts"],
        }),
      );
      const result = spawnSync(TSC, ["-p", join(dir, "tsconfig.json")], { encoding: "utf8" });
      expect(result.stdout + result.stderr).toBe("");
      expect(result.status).toBe(0);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});
